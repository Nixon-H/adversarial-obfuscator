"""
challenge_response.py

Purpose:
Standalone challenge-response authentication protocol extracted from the
distributed attestation framework. Provides mutual verification between
peers using SHA-256-based challenge/response exchanges with timing
jitter and self-destruct on excessive failures.

Architectural Role:
Runtime authentication layer. Used to verify peer identity before
exchanging sensitive data or delegating protected operations. Can
operate independently of the full distributed attestation system.

Security Relevance:
This is a first-party authentication primitive. The protocol:
- Uses per-peer secrets derived from SHA-256(peer_id || random_salt)
  to ensure uniqueness and unpredictability.
- Includes timing jitter (uniform random up to 10% of timeout) to
  prevent timing-based fingerprinting of the challenge generation.
- Implements a self-destruct mechanism after max_failures consecutive
  authentication failures, preventing brute-force enumeration.
- Uses random nonces for each challenge/response to prevent replay.
- Response includes a proof-of-possession of the shared secret.

Threat model: Impersonation, replay, timing side-channels, brute-force.

What happens on failure: self._self_destructed = True permanently locks
the instance, rejecting all further operations. Caller should create a
new instance or escalate to administrative intervention.
"""

import hashlib
import os
import random
import struct
import time
from dataclasses import dataclass
from typing import Optional


@dataclass
class Challenge:
    """
    A challenge issued by a challenger to a responder.

    Contains the raw challenge data (nonce + signature), timestamps
    for deadline enforcement, and the identity of the challenger.
    The deadline includes jitter to frustrate timing attacks.
    """
    challenger_id: str
    challenge_data: bytes
    timestamp: float
    deadline: float


@dataclass
class Response:
    """
    A response to a challenge, generated by the responder.

    Contains proof data derived from the shared secret. success=False
    indicates the challenge was invalid or the deadline expired.
    """
    responder_id: str
    response_data: bytes
    timestamp: float
    success: bool


class ChallengeResponse:
    """
    Challenge-response authentication protocol.

    Implements a three-message authentication handshake:
      1. create_challenge(responder_id) -> Challenge
      2. respond_to_challenge(responder_id, challenge) -> Response
      3. verify_response(challenge, response) -> bool

    Each peer maintains per-peer secrets derived from the peer ID and
    fresh random entropy. Self-destruct triggers after max_failures.
    """

    def __init__(self, timeout: float = 5.0, max_failures: int = 3):
        """
        Initialize the protocol handler.

        Args:
            timeout: Deadline for challenge validity in seconds.
            max_failures: Consecutive failures before self-destruct.
        """
        self.timeout = timeout
        self.max_failures = max_failures
        self._secrets: dict[str, bytes] = {}
        self._failed_attestations: dict[str, int] = {}
        self._self_destructed = False

    def _get_secret(self, peer_id: str) -> bytes:
        """
        Derive or retrieve a per-peer shared secret.

        Secret = SHA-256(peer_id || 32 random bytes). Derived once
        and cached. The random salt ensures forward secrecy: past
        secrets cannot be recomputed after restart.

        Security note: bytes are immutable, so the secret cannot be
        explicitly zeroed. Caller should minimize retention.
        """
        if peer_id not in self._secrets:
            self._secrets[peer_id] = hashlib.sha256(
                peer_id.encode() + os.urandom(32)
            ).digest()
        return self._secrets[peer_id]

    def create_challenge(self, responder_id: str) -> Optional[Challenge]:
        """
        Create a fresh authentication challenge for a responder.

        The challenge contains:
        - responder_id || 16-byte nonce (challenge data)
        - SHA-256(secret || challenge_data) (signature)

        A random jitter is added to the deadline to prevent an attacker
        from using response timing to infer secret properties.
        """
        if self._self_destructed:
            return None

        secret = self._get_secret(responder_id)

        nonce = os.urandom(16)
        challenge_data = responder_id.encode() + nonce

        challenge_sig = hashlib.sha256(secret + challenge_data).digest()
        full_challenge = challenge_data + challenge_sig

        jitter = random.uniform(0, max(0.001, self.timeout * 0.1))
        deadline = time.time() + self.timeout + jitter

        return Challenge(
            challenger_id="local",
            challenge_data=full_challenge,
            timestamp=time.time(),
            deadline=deadline,
        )

    def respond_to_challenge(self, responder_id: str, challenge: Challenge) -> Optional[Response]:
        """
        Validate an incoming challenge and produce a signed response.

        Steps:
        1. Check self-destruct flag.
        2. Apply small timing jitter to mask computation time.
        3. Verify the challenge's SHA-256 signature using the shared secret.
        4. If valid, generate a response nonce and sign with secret + "OK".
        5. Track failures; trigger self-destruct at threshold.

        Security note: The timing jitter in step 2 is critical to
        prevent timing attacks that could leak the secret comparison
        result.
        """
        if self._self_destructed:
            return None

        time.sleep(random.uniform(0, 0.01))

        secret = self._get_secret(responder_id)

        if time.time() > challenge.deadline:
            self._failed_attestations[responder_id] = self._failed_attestations.get(responder_id, 0) + 1
            return Response(responder_id, b"", time.time(), False)

        challenge_data = challenge.challenge_data[:-32]
        challenge_sig = challenge.challenge_data[-32:]

        expected_sig = hashlib.sha256(secret + challenge_data).digest()
        if challenge_sig != expected_sig:
            self._failed_attestations[responder_id] = self._failed_attestations.get(responder_id, 0) + 1
            return Response(responder_id, b"", time.time(), False)

        response_nonce = os.urandom(16)
        response_data = challenge_data + response_nonce
        response_sig = hashlib.sha256(secret + response_data + b"OK").digest()

        if self._failed_attestations.get(responder_id, 0) >= self.max_failures:
            self._self_destructed = True

        return Response(
            responder_id=responder_id,
            response_data=response_data + response_sig,
            timestamp=time.time(),
            success=True,
        )

    def verify_response(self, challenge: Challenge, response: Response) -> bool:
        """
        Verify a responder's response to a previously issued challenge.

        Checks:
        1. Self-destruct not triggered.
        2. Response received within timeout window.
        3. Response.success flag is True.
        4. SHA-256(secret || response_data || "OK") matches the signature.

        Security note: This uses constant-time comparison only implicitly
        through hashlib. If timing attacks are a concern, replace with
        hmac.compare_digest on the final comparison.
        """
        if self._self_destructed:
            return False

        if time.time() > response.timestamp + self.timeout:
            return False

        if not response.success:
            return False

        secret = self._get_secret(response.responder_id)
        response_data = response.response_data[:-32]
        response_sig = response.response_data[-32:]

        expected_sig = hashlib.sha256(secret + response_data + b"OK").digest()
        return response_sig == expected_sig

    def run_pairwise(self, peer_ids: list[str]) -> dict[tuple[str, str], bool]:
        """
        Run challenge-response authentication for every pair in a list.

        Each pair (a, b) is tested with a acting as challenger and b
        as responder. Returns a dict of (a_id, b_id) -> verified bool.
        """
        results = {}
        for i, a in enumerate(peer_ids):
            for b in peer_ids[i + 1:]:
                challenge = self.create_challenge(b)
                if challenge is None:
                    results[(a, b)] = False
                    continue
                response = self.respond_to_challenge(b, challenge)
                if response is None:
                    results[(a, b)] = False
                    continue
                verified = self.verify_response(challenge, response)
                results[(a, b)] = verified
        return results

    def is_self_destructed(self) -> bool:
        """Return whether the handler has permanently locked itself."""
        return self._self_destructed
