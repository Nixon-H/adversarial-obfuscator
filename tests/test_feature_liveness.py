class TestArtefactManifest:
    def test_manifest_round_trip(self, tmp_path):
        from scripts.artifacts import manifest
        artefact = tmp_path / "obfuscated.py"
        # The per-build hardening renames the loader's symbols, so the
        # manifest reports the two things that survive renaming: an HMAC
        # over the payload and an integrity verification step.
        artefact.write_text(
            "import hmac\n"
            "def _nx_verify():\n"
            "    pass\n"
        )
        path = manifest.write_manifest(str(tmp_path), str(artefact))
        data = json.loads(open(path).read())
        assert data["artefact"]["exists"] is True
        assert data["artefact"]["sha256"]
        assert "payload_mac" in data["loader_gates"]
        assert "self_integrity" in data["loader_gates"]

    def test_a_gutted_artefact_reports_no_gates(self, tmp_path):
        """Absence has to be meaningful, or the field is decoration."""
        from scripts.artifacts import manifest
        artefact = tmp_path / "obfuscated.py"
        artefact.write_text("print('no gates here')\n")
        path = manifest.write_manifest(str(tmp_path), str(artefact))
        data = json.loads(open(path).read())
        assert data["loader_gates"] == []

    def test_missing_artefact_is_recorded_honestly(self, tmp_path):
        from scripts.artifacts import manifest
        path = manifest.write_manifest(str(tmp_path), str(tmp_path / "absent.py"))
        data = json.loads(open(path).read())
        assert data["artefact"]["exists"] is False
        assert data["loader_gates"] == []

    def test_manifest_absence_means_unverified_not_live(self, tmp_path):
        """A build dir with no manifest must not yield LIVE features."""
        result = subprocess.run(
            [sys.executable, "scripts/classify_features.py", "--json",
             "--from-build", str(tmp_path)],
            capture_output=True, text=True, timeout=180, cwd=ROOT,
        )
        assert result.returncode == 0, result.stderr
        report = json.loads(result.stdout)
        assert report["artefact_manifest"] is False
        live = [f["id"] for f in report["features"] if f["classification"] == "LIVE"]
        assert live == [], f"LIVE without an artefact manifest: {live}"


class TestRequireLiveGate:
    def test_gate_fails_when_nothing_is_live(self):
        result = subprocess.run(
            [sys.executable, "scripts/classify_features.py", "--json",
             "--require-live", "1"],
            capture_output=True, text=True, timeout=180, cwd=ROOT,
        )
        assert result.returncode == 1, "the gate did not fail with 0 LIVE features"
        assert "LIVE feature" in result.stderr

    def test_gate_passes_at_zero_threshold(self):
        result = subprocess.run(
            [sys.executable, "scripts/classify_features.py", "--json",
             "--require-live", "0"],
            capture_output=True, text=True, timeout=180, cwd=ROOT,
        )
        assert result.returncode == 0


class TestReportShape:
    def test_report_states_whether_evidence_was_available(self):
        report = _report()
        assert "artefact_manifest" in report, \
            "the report must say whether it had artefact evidence"
        assert report["report_version"] != "1.0", "report claims the old version"
