"""Feature liveness: does the report reflect the artefact or a name match?

The classification report is the document people quote.  It used to be
generated by checking that a file with a similar name existed, and it
returned IMPLEMENTED for everything.  These tests pin the properties
that make it trustworthy:

* a module may only count as reachable if the call graph reaches it;
* "LIVE" needs artefact evidence, not a declaration;
* a claimed-live feature with no evidence fails the build.

Each test here fails against the pre-fix classifier.
"""
import json
import os
import subprocess
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))


def _report():
    result = subprocess.run(
        [sys.executable, "scripts/classify_features.py", "--json"],
        capture_output=True, text=True, timeout=180, cwd=ROOT,
    )
    assert result.returncode == 0, result.stderr
    return json.loads(result.stdout)


class TestCallGraphIsNotANameMatch:
    """The old check asked whether a module NAME appeared in lib.rs.
    That is how 12 modules were reported as implemented while being
    unreachable from init_runtime.

    Those modules were archived on 2026-10-23 (see
    archive/rust-runtime/README.md), so the invariant is now the
    inverse: nothing declared may be unreachable, and the archived ones
    must not be compiled.
    """

    def test_archived_unreachable_modules_are_gone(self):
        from scripts.reachability import rust_callgraph as cg
        declared = cg.module_declarations()
        for name in ("rop", "oram", "hwid_bind", "code_genome"):
            assert name not in declared, \
                f"{name} is archived and must not be declared in lib.rs"

    def test_walker_excludes_a_declared_but_unreferenced_module(self):
        """The whole point: a name in lib.rs is not a call path."""
        from scripts.reachability import rust_callgraph as cg
        synthetic = (
            "pub mod live_one;\n"
            "pub mod dead_one;\n"
            "\n"
            "pub fn init_runtime() {\n"
            "    live_one::go();\n"
            "}\n"
        )
        declared = cg.module_declarations(synthetic)
        assert declared == {"live_one", "dead_one"}
        assert cg.unreachable_modules(synthetic) == {"dead_one"}

    def test_init_runtime_actually_parsed(self):
        from scripts.reachability import rust_callgraph as cg
        body = cg.init_runtime_body()
        assert len(body) > 1000, "failed to extract init_runtime body"
        assert "selfdestruct" in body


