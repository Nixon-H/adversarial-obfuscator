use std::path::PathBuf;

fn decode_build_seed(value: &str) -> Option<String> {
    let bytes = value.as_bytes();
    if bytes.len() != 64 || !bytes.iter().all(u8::is_ascii_hexdigit) {
        return None;
    }
    Some(value.to_ascii_lowercase())
}

/// A build-time seed: NIXON_BUILD_SEED (64 hex chars) when set, otherwise
/// 32 bytes from the OS RNG. Invalid explicit configuration fails the build;
/// there is no time/hash fallback.
fn fresh_build_seed() -> Result<String, Box<dyn std::error::Error>> {
    match std::env::var("NIXON_BUILD_SEED") {
        Ok(value) => decode_build_seed(value.trim())
            .ok_or_else(|| "NIXON_BUILD_SEED must be 64 ASCII hex characters".into()),
        Err(std::env::VarError::NotPresent) => os_entropy_seed(),
        Err(std::env::VarError::NotUnicode(_)) => Err("NIXON_BUILD_SEED must be ASCII hex".into()),
    }
}

#[cfg(unix)]
fn os_entropy_seed() -> Result<String, Box<dyn std::error::Error>> {
    use std::io::Read;
    let mut file = std::fs::File::open("/dev/urandom")?;
    let mut bytes = [0u8; 32];
    file.read_exact(&mut bytes)?;
    Ok(bytes.iter().map(|byte| format!("{byte:02x}")).collect())
}

#[cfg(not(unix))]
fn os_entropy_seed() -> Result<String, Box<dyn std::error::Error>> {
    Err("OS entropy unavailable: set NIXON_BUILD_SEED".into())
}

/// Replace the manifest's build_seed string without reformatting the rest of
/// the document. The runtime manifest is build input, not generated source.
fn inject_build_seed(content: &str, seed: &str) -> Result<String, Box<dyn std::error::Error>> {
    const KEY: &str = "\"build_seed\"";
    let mut matches = content.match_indices(KEY);
    let key_start = matches
        .next()
        .ok_or("runtime manifest has no build_seed field")?
        .0;
    if matches.next().is_some() {
        return Err("runtime manifest has duplicate build_seed fields".into());
    }
    let after_key = &content[key_start + KEY.len()..];
    let colon = after_key
        .find(':')
        .ok_or("runtime manifest build_seed has no colon")?;
    let after_colon = &after_key[colon + 1..];
    let quote_offset = after_colon
        .find('"')
        .ok_or("runtime manifest build_seed is not a string")?;
    let value_start = key_start + KEY.len() + colon + 1 + quote_offset;
    let value_end = content[value_start + 1..]
        .find('"')
        .map(|offset| value_start + 1 + offset)
        .ok_or("runtime manifest build_seed string is unterminated")?;
    let mut output = String::with_capacity(content.len() + seed.len());
    output.push_str(&content[..value_start + 1]);
    output.push_str(seed);
    output.push_str(&content[value_end..]);
    Ok(output)
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=../runtime/manifest.json");
    println!("cargo:rerun-if-env-changed=NIXON_BUILD_SEED");
    println!("cargo:rerun-if-env-changed=DEP_SIMD_VM_ARCHIVE");
    // MinGW does not reliably propagate a dependency's native static library
    // by short name. The runtime exports the target-specific archive path.
    if let Ok(archive) = std::env::var("DEP_SIMD_VM_ARCHIVE") {
        println!("cargo:rustc-link-arg={archive}");
    }

    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR")?;
    let manifest_path = PathBuf::from(manifest_dir);
    let runtime_manifest = manifest_path
        .parent()
        .map(|path| path.join("runtime").join("manifest.json"))
        .filter(|path| path.exists());
    let out_dir = std::env::var("OUT_DIR")?;
    let out_file = PathBuf::from(out_dir).join("config_embed.rs");

    let content = match runtime_manifest {
        Some(path) => {
            let manifest = std::fs::read_to_string(path)?;
            inject_build_seed(&manifest, &fresh_build_seed()?)?
        }
        None => String::new(),
    };
    let encoded: Vec<u8> = content.bytes().collect();
    let output = format!(
        "// Auto-generated by build.rs. Do not edit.\npub const RUNTIME_MANIFEST: &[u8] = &{encoded:?};\n"
    );
    std::fs::write(out_file, output)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn explicit_seed_is_normalized_and_validated() {
        assert_eq!(
            decode_build_seed(&"AB".repeat(32)).as_deref(),
            Some("ab".repeat(32).as_str())
        );
        assert!(decode_build_seed(&"a".repeat(63)).is_none());
        assert!(decode_build_seed(&"é".repeat(64)).is_none());
    }

    #[test]
    fn seed_injection_replaces_existing_value_only() {
        let input = "{\n  \"build_seed\": \"old\",\n  \"version\": 1\n}\n";
        let output = inject_build_seed(input, &"11".repeat(32)).unwrap();
        assert!(output.contains(&format!("\"build_seed\": \"{}\"", "11".repeat(32))));
        assert!(output.contains("\"version\": 1"));
        assert!(!output.contains("old"));
    }

    #[test]
    fn missing_seed_field_is_an_error() {
        assert!(inject_build_seed("{}", &"11".repeat(32)).is_err());
    }
}
