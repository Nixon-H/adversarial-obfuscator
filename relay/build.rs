fn main() {
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").unwrap();
    let manifest_path = std::path::Path::new(&manifest_dir);

    let runtime_manifest = manifest_path
        .parent()
        .map(|p| p.join("runtime").join("manifest.json"))
        .filter(|p| p.exists());

    let out_dir = manifest_path.join("src");
    let out_file = out_dir.join("config_embed.rs");

    if let Some(path) = runtime_manifest {
        let content = std::fs::read_to_string(&path).unwrap_or_default();
        let encoded: Vec<u8> = content.bytes().collect();
        let output = format!(
            "// Auto-generated by build.rs. Do not edit.\npub const RUNTIME_MANIFEST: &[u8] = &{:?};\n",
            encoded
        );
        std::fs::write(&out_file, output).unwrap();
    } else {
        let output = "\
// Auto-generated by build.rs. Do not edit.
pub const RUNTIME_MANIFEST: &[u8] = &[];
";
        std::fs::write(&out_file, output).unwrap();
    }

    println!("cargo:rerun-if-changed=../runtime/manifest.json");
}
